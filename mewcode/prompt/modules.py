def _render(m: Module) -> str:
    """单个模块渲染成文本：## 标题 + 正文。"""
    return f"## {m.title}\n{m.body}"


# 七模块整体拼接（模块间空行分隔）——系统提示的稳定部分，每轮逐字节一致
