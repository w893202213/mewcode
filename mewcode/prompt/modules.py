from dataclasses import dataclass


@dataclass(frozen=True)
class Module:
    """系统提示的一个模块：标题（二级 Markdown 标题）＋正文。"""

    title: str  # 如 "身份"（拼装时以 "## " 前缀输出）
    body: str  # 模块正文（多条规则按行排列）


